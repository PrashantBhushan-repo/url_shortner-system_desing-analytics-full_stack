import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const base = 'http://127.0.0.1:5234';
const browser = await chromium.launch({ headless:true, ...(process.env.PLAYWRIGHT_CHROMIUM_PATH ? { executablePath:process.env.PLAYWRIGHT_CHROMIUM_PATH } : {}) });
const context = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const page = await context.newPage();
page.setDefaultTimeout(12000);
const errors = [];
const passed = [];
page.on('pageerror',error=>errors.push(error.message));
const output = new URL('../../image/workspace-preview/navigation/',import.meta.url);
await fs.mkdir(output,{recursive:true});
const shot = async name => { await page.waitForTimeout(250); await page.screenshot({path:fileURLToPath(new URL(name+'.png',output)),fullPage:false}); };
try {
  await page.goto(base+'/');
  await page.getByRole('heading',{level:1}).waitFor();
  await page.getByRole('navigation',{name:'Main navigation',exact:true}).getByRole('link',{name:'Pricing',exact:true}).click();
  await page.waitForURL('**/pricing');
  passed.push('Website navigation opens the complete pricing page');
  await page.goto(base+'/demo');
  await page.getByRole('navigation',{name:'Choose demo experience',exact:true}).getByRole('link',{name:'Admin console',exact:true}).click();
  await page.waitForURL('**/demo/admin');
  passed.push('Public demos remain reachable without authentication');
  await page.goto(base+'/settings?tab=apiKeys');
  await page.waitForURL('**/auth?**');
  assert.equal(new URL(page.url()).searchParams.get('next'),'/settings?tab=apiKeys');
  await page.getByRole('button',{name:/Create an account/i}).count().then(async count=>{ if(count) { await page.getByRole('button',{name:/Create an account/i}).click(); assert.equal(new URL(page.url()).searchParams.get('next'),'/settings?tab=apiKeys'); await page.getByRole('button',{name:/Sign in/i,exact:true}).last().click(); } });
  await page.getByLabel('Email address',{exact:true}).fill('sam@example.invalid');
  await page.getByLabel('Password',{exact:true}).fill('Testing123!');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.waitForURL('**/settings/api-keys');
  await page.getByRole('heading',{name:'API keys',exact:true}).waitFor();
  passed.push('Protected deep link survives sign-in and legacy redirect');
  await page.getByRole('navigation',{name:'Workspace navigation',exact:true}).getByRole('link',{name:'Billing',exact:true}).click();
  await page.waitForURL('**/billing');
  await page.goBack(); await page.waitForURL('**/settings/api-keys');
  passed.push('Billing and settings browser back navigation');
  await page.evaluate(()=>sessionStorage.setItem('pburls:auth-return','/settings/security'));
  await page.goto(base+'/oauth/callback?token=navigation-qa-session');
  await page.waitForURL('**/settings/security');
  assert.equal(new URL(page.url()).searchParams.has('token'),false);
  passed.push('OAuth callback restores the intended section and clears its callback URL');
  await page.goto(base+'/admin/reconcile');
  await page.getByRole('heading',{name:'This page needs administrator access.',exact:true}).waitFor();
  passed.push('User role cannot open administrator pages');
  await page.goto(base+'/dashboard?q=launch&status=Expired&sort=clicks');
  await page.getByRole('textbox',{name:'Search your links',exact:true}).waitFor();
  assert.equal(await page.getByRole('textbox',{name:'Search your links',exact:true}).inputValue(),'launch');
  await page.getByRole('textbox',{name:'Search your links',exact:true}).fill('campaign');
  await page.waitForURL(url=>url.searchParams.get('q')==='campaign');
  assert.equal(new URL(page.url()).searchParams.get('status'),'Expired');
  await page.reload();
  assert.equal(await page.getByRole('combobox',{name:'Sort your links',exact:true}).inputValue(),'clicks');
  passed.push('Link filters persist across reload and preserve one another');
  await page.goto(base+'/pricing?plan=starter&cycle=YEARLY');
  await page.getByRole('button',{name:'Review Starter',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  assert.match(await page.getByRole('dialog').innerText(),/for 12 months/);
  assert.equal(await page.getByRole('dialog').getByRole('button',{name:/Starter/}).getAttribute('aria-pressed'),'true');
  await page.getByRole('button',{name:'Close dialog',exact:true}).click();
  passed.push('Pricing reviews the selected plan and cycle in shared checkout');
  await shot('pricing-desktop');
  await page.goto(base+'/help#billing');
  await page.getByRole('heading',{name:'Plans, payments, and refunds',exact:true}).waitFor();
  await page.waitForTimeout(150);
  assert.ok(await page.locator('#billing').evaluate(el=>el.getBoundingClientRect().top>=75));
  await page.getByRole('searchbox',{name:'Search help guides',exact:true}).fill('not-a-matching-guide');
  await page.getByRole('heading',{name:/No guides match/}).waitFor();
  passed.push('Help anchors and search are usable');
  await page.goto(base+'/a-missing-page');
  await page.getByRole('heading',{name:'Let’s get you back on track.',exact:true}).waitFor();
  passed.push('Unknown routes show recovery navigation');
  await page.goto(base+'/settings/billing/');
  await page.waitForURL('**/billing');
  await page.getByRole('heading',{name:'Plans & billing',exact:true}).waitFor();
  assert.equal(await page.getByLabel('Settings navigation',{exact:true}).count(),0);
  assert.equal(await page.locator('main').getByRole('link',{name:'Password',exact:true}).count(),0);
  assert.equal(await page.locator('main').getByRole('link',{name:'Profile',exact:true}).count(),0);
  assert.equal(await page.title(),'Plans & billing | PBUrls');
  assert.equal(await page.getByRole('navigation',{name:'Workspace navigation',exact:true}).getByRole('link',{name:'Billing',exact:true}).getAttribute('aria-current'),'page');
  await shot('billing-desktop');
  passed.push('Billing has a dedicated page without account settings navigation');
  await page.goto(base+'/settings?tab=subscription&coupon=SAVE#history');
  await page.waitForURL('**/billing?coupon=SAVE#history');
  passed.push('Legacy billing links preserve query values and anchors');
  await page.goto(base+'/settings/profile');
  await page.getByLabel('Settings navigation',{exact:true}).getByRole('link',{name:'Password',exact:true}).click();
  await page.waitForURL('**/settings/password');
  await page.getByRole('heading',{name:'Password',exact:true}).waitFor();
  assert.equal(await page.locator('.billing-console').count(),0);
  assert.equal(await page.getByLabel('Settings navigation',{exact:true}).getByRole('link',{name:'Plans & billing',exact:true}).count(),0);
  passed.push('Account settings stay separate from the billing console');
  passed.push('Trailing slash URLs redirect to canonical pages');
  await page.goto(base+'/p/QAlink1?error=true');
  await page.getByRole('heading',{name:/A password is needed/}).waitFor();
  await page.getByLabel('Link password',{exact:true}).fill('qa-only-password');
  await page.getByRole('button',{name:'Open destination',exact:true}).click();
  await page.waitForURL('**/r/QAlink1?**');
  assert.match(await page.locator('body').innerText(),/testGateway/);
  passed.push('Protected links navigate to the configured redirect gateway');
  await page.goto(base+'/settings/billing');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('heading',{name:'Plans & billing',exact:true}).waitFor();
  await page.getByRole('button',{name:'Open navigation',exact:true}).click();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('button',{name:'Open navigation',exact:true}).getAttribute('aria-expanded'),'false');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await shot('billing-mobile-dark');
  await page.getByRole('button',{name:'Switch color theme',exact:true}).click();
  await shot('billing-mobile-light');
  passed.push('Mobile menu, Escape key, themes, and overflow checks');
  await context.request.get(base+'/__navigation_qa/session?role=admin');
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base+'/admin/reconcile');
  await page.getByRole('heading',{name:'Automatic payment recovery',exact:true}).waitFor();
  await page.reload();
  await page.getByRole('heading',{name:'Automatic payment recovery',exact:true}).waitFor();
  assert.equal(new URL(page.url()).pathname,'/admin/reconcile');
  assert.equal(await page.locator('nav[aria-label="Administration sections"] a').count(),11);
  await shot('admin-desktop');
  passed.push('Administrator deep links, refresh, and all section destinations');
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.waitForURL(url=>url.pathname==='/auth'&&!url.searchParams.has('next'));
  await page.goto(base+'/settings/billing');
  await page.waitForURL('**/auth?**');
  passed.push('Sign-out clears workspace access');
  assert.deepEqual(errors,[]);
  passed.push('No uncaught browser errors in tested flows');
  await fs.writeFile(new URL('results.json',output),JSON.stringify({passed,errors},null,2));
  console.log(JSON.stringify({passed:passed.length,checks:passed},null,2));
} catch (error) {
  await page.screenshot({path:fileURLToPath(new URL('failure.png',output)),fullPage:false}).catch(()=>{});
  console.error(JSON.stringify({url:page.url(),completed:passed,errors,body:(await page.locator('body').innerText().catch(()=>'' )).slice(0,1600)}));
  throw error;
} finally { await context.close(); await browser.close(); }
